/*
 * Accessories (ADR-155): funny things a player buys with game money and wears on the pixel figure. One per slot,
 * other players see them on the profile and on the friends plaza. Keys are stored in the database and must never
 * change; prices are paid once, there is no resale. The pixel art lives in src/components/pixel/accessories.ts.
 *
 * Purity rules (ADR-012): no imports, JSON-serialisable values only (this file is part of BALANCE).
 */

/** Drawing order on the figure, back to front: wings behind the body, the pet last. */
export const ACCESSORY_SLOTS = ["back", "body", "face", "head", "hand", "pet"] as const;
export type AccessorySlot = (typeof ACCESSORY_SLOTS)[number];

/** Rarity tiers, cheapest first; every tier costs more than all items of the tier below. */
export const ACCESSORY_RARITIES = ["common", "rare", "epic", "legendary", "mythic"] as const;
export type AccessoryRarity = (typeof ACCESSORY_RARITIES)[number];

/** Themed sets (only for grouping in the wardrobe, no bonus): matching things to combine. */
export const ACCESSORY_SETS = [
  "pirate",
  "space",
  "knight",
  "wizard",
  "chef",
  "rock",
  "sports",
  "zoo",
  "holidays",
  "office",
  "absurd",
  "royal",
] as const;
export type AccessorySet = (typeof ACCESSORY_SETS)[number];

export interface AccessoryItem {
  readonly key: string;
  readonly name: string;
  /** One short, funny German line for the shop. */
  readonly description: string;
  readonly slot: AccessorySlot;
  readonly rarity: AccessoryRarity;
  readonly priceCents: number;
  /** Shown from level 1, buyable from this level. */
  readonly minLevel: number;
  /** Themed set for grouping in the shop (optional). */
  readonly set?: AccessorySet;
}

const item = (
  key: string,
  slot: AccessorySlot,
  rarity: AccessoryRarity,
  priceCents: number,
  minLevel: number,
  name: string,
  description: string,
  set?: AccessorySet,
): AccessoryItem => ({ key, name, description, slot, rarity, priceCents, minLevel, ...(set ? { set } : {}) });

