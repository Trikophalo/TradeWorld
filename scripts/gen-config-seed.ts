/**
 * Writes supabase/seeds/game_config.sql from src/config/balance.ts
 * (docs/DECISIONS.md, ADR-009). One row per top-level section.
 *
 * The statement only inserts missing keys. Values an admin changed at runtime
 * are never overwritten by re-seeding; to reset a section, delete its row first.
 *
 * Run with `pnpm db:config` after every change to balance.ts.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BALANCE } from "../src/config/balance";

/** Sections players may read (fees, tax, vault, unlocks). Simulation parameters stay server-only. */
const PUBLIC_KEYS = ["time", "economy", "trading", "bonds", "company", "careers", "progression", "lifestyle"];

const quote = (text: string) => `'${text.replace(/'/g, "''")}'`;

const rows = Object.entries(BALANCE).map(([key, value]) => {
  const json = JSON.stringify(value, (_key, v) => (typeof v === "bigint" ? Number(v) : v));
  return `  (${quote(key)}, ${quote(json)}::jsonb, ${quote(`Defaults from src/config/balance.ts, section "${key}"`)})`;
});

const sql = `-- GENERATED by scripts/gen-config-seed.ts from src/config/balance.ts. Do not edit by hand.
-- Apply after the migrations: psql -f supabase/seeds/game_config.sql

insert into public.game_config (key, value, description) values
${rows.join(",\n")}
on conflict (key) do nothing;

insert into public.game_config_public_keys (key) values
${PUBLIC_KEYS.map((key) => `  (${quote(key)})`).join(",\n")}
on conflict (key) do nothing;
`;

const dir = join(process.cwd(), "supabase", "seeds");
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "game_config.sql"), sql);
console.log(`game_config.sql: ${rows.length} sections, ${sql.length} bytes`);
