#!/usr/bin/env bash
# Builds supabase/setup-all.sql: all migrations, seed.sql and the generated
# game_config seed in one transaction, for pasting into the Supabase SQL Editor.
# Run after any change to migrations, seed.sql or balance.ts (pnpm db:config first).
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/setup-all.sql
{
  echo "-- NEXA: complete database setup in one file. GENERATED by scripts/build-setup-sql.sh, do not edit."
  echo "-- Paste into the Supabase SQL Editor of an EMPTY project and run once."
  echo "begin;"
  for f in supabase/migrations/*.sql supabase/seed.sql supabase/seeds/game_config.sql; do
    echo
    echo "-- ===== $f ====="
    cat "$f"
  done
  echo
  echo "commit;"
} > "$out"
echo "$out: $(wc -c < "$out") bytes"

# Seeds only: for a project whose tables were already created from the migrations
# (for example by the Supabase GitHub integration). Both seed files are idempotent.
seeds=supabase/setup-seeds.sql
{
  echo "-- NEXA: reference data and game config only. GENERATED by scripts/build-setup-sql.sh, do not edit."
  echo "-- For a project whose tables already exist. Safe to run more than once."
  echo "begin;"
  for f in supabase/seed.sql supabase/seeds/game_config.sql; do
    echo
    echo "-- ===== $f ====="
    cat "$f"
  done
  echo
  echo "commit;"
} > "$seeds"
echo "$seeds: $(wc -c < "$seeds") bytes"

# Update for a database set up with an older setup-all.sql: applies every later
# schema change idempotently and replaces the game config with the current values.
update=supabase/update-to-latest.sql
{
  echo "-- NEXA: bring an existing database up to date. GENERATED by scripts/build-setup-sql.sh, do not edit."
  echo "-- Safe to run more than once. Overwrites game_config with the values from src/config/balance.ts."
  echo "begin;"
  echo
  cat supabase/updates/*.sql
  echo
  echo "-- ===== game_config (current values, overwriting older ones) ====="
  sed 's/^on conflict (key) do nothing;$/on conflict (key) do UPDATE_PLACEHOLDER/' supabase/seeds/game_config.sql \
    | awk 'BEGIN{n=0} /UPDATE_PLACEHOLDER/{n++; if(n==1){print "on conflict (key) do update set value = excluded.value, description = excluded.description, updated_at = now();"; next} else {print "on conflict (key) do nothing;"; next}} {print}'
  echo
  echo "commit;"
} > "$update"
echo "$update: $(wc -c < "$update") bytes"
