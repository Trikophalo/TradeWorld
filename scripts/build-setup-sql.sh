#!/usr/bin/env bash
# Builds supabase/setup-all.sql: all migrations, seed.sql and the generated
# game_config seed in one transaction, for pasting into the Supabase SQL Editor.
# Run after any change to migrations, seed.sql or balance.ts (pnpm db:config first).
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/setup-all.sql
# M1: after schema, seeds and config exist, start the market (fair values,
# bond series, price history only if no candles exist, day statistics).
# Idempotent; run_due_jobs() would do it lazily as well.
bootstrap="-- ===== market bootstrap (M1) =====
select public.market_bootstrap();"
{
  echo "-- NEXA: complete database setup in one file. GENERATED by scripts/build-setup-sql.sh, do not edit."
  echo "-- Paste into the Supabase SQL Editor of an EMPTY project and run once."
  echo "begin;"
  for f in supabase/migrations/*.sql supabase/seed.sql supabase/seeds/game_config.sql; do
    echo
    echo "-- ===== $f ====="
    cat "$f"
  done
  echo
  echo "$bootstrap"
  echo
  echo "commit;"
} > "$out"
echo "$out: $(wc -c < "$out") bytes"

# Seeds only: for a project whose tables were already created from the migrations
# (for example by the Supabase GitHub integration). Both seed files are idempotent.
seeds=supabase/setup-seeds.sql
{
  echo "-- NEXA: reference data and game config only. GENERATED by scripts/build-setup-sql.sh, do not edit."
  echo "-- For a project whose tables already exist. Safe to run more than once."
  echo "begin;"
  for f in supabase/seed.sql supabase/seeds/game_config.sql; do
    echo
    echo "-- ===== $f ====="
    cat "$f"
  done
  echo
  echo "commit;"
} > "$seeds"
echo "$seeds: $(wc -c < "$seeds") bytes"

# Update for a database set up with an older setup-all.sql: applies every later
# schema change idempotently and replaces the game config with the current values.
update=supabase/update-to-latest.sql
{
  echo "-- NEXA: bring an existing database up to date. GENERATED by scripts/build-setup-sql.sh, do not edit."
  echo "-- Safe to run more than once. Overwrites game_config with the values from src/config/balance.ts."
  echo "begin;"
  echo "-- Wait for a running market tick, then keep the scheduled jobs out until commit (avoids deadlocks)."
  echo "select pg_advisory_xact_lock(7311001);"
  echo
  cat supabase/updates/*.sql
  echo
  echo "-- ===== game_config (current values, overwriting older ones) ====="
  sed 's/^on conflict (key) do nothing;$/on conflict (key) do UPDATE_PLACEHOLDER/' supabase/seeds/game_config.sql \
    | awk 'BEGIN{n=0} /UPDATE_PLACEHOLDER/{n++; if(n==1){print "on conflict (key) do update set value = excluded.value, description = excluded.description, updated_at = now();"; next} else {print "on conflict (key) do nothing;"; next}} {print}'
  echo
  echo "$bootstrap"
  echo
  echo "commit;"
} > "$update"
echo "$update: $(wc -c < "$update") bytes"

# The Supabase SQL Editor refuses large queries. Split both files into numbered parts
# (whole files only, each part its own transaction), to run one after the other.
limit=200000
parts=supabase/sql-editor
rm -rf "$parts"
mkdir -p "$parts"

# write_parts <prefix> <header-lines> <files...>: groups the files into parts below the limit.
write_parts() {
  local prefix=$1 header=$2
  shift 2
  local n=1 size=0 current=""
  flush() {
    [ -z "$current" ] && return
    # Own loop variable: the caller's $f must survive (bash scopes dynamically).
    local file part
    file=$(printf "%s/%s-%02d.sql" "$parts" "$prefix" "$n")
    {
      echo "-- NEXA: part $n of the $prefix. GENERATED by scripts/build-setup-sql.sh, do not edit."
      echo "-- Run the parts in order in the Supabase SQL Editor, one after the other."
      echo "begin;"
      printf "%b\n" "$header"
      for part in $current; do
        echo
        echo "-- ===== $part ====="
        cat "$part"
      done
      echo
      echo "commit;"
    } > "$file"
    n=$((n + 1))
    size=0
    current=""
  }
  for f in "$@"; do
    local s
    s=$(wc -c < "$f")
    if [ $((size + s)) -gt $limit ] && [ -n "$current" ]; then flush; fi
    current="$current $f"
    size=$((size + s))
  done
  flush
}

lock="-- Wait for a running market tick, keep scheduled jobs out until commit (avoids deadlocks).\nselect pg_advisory_xact_lock(7311001);"
write_parts update "$lock" supabase/updates/*.sql
# Last update part: current game config and the market bootstrap.
n_update=$(ls "$parts"/update-*.sql | wc -l)
last=$(printf "%s/update-%02d.sql" "$parts" "$((n_update + 1))")
{
  echo "-- NEXA: part $((n_update + 1)) of the update (last). GENERATED by scripts/build-setup-sql.sh, do not edit."
  echo "begin;"
  echo "select pg_advisory_xact_lock(7311001);"
  echo
  sed -n '/^-- ===== game_config (current values/,/^commit;$/p' "$update" | sed '$d'
  echo "commit;"
} > "$last"

write_parts setup "" supabase/migrations/*.sql supabase/seed.sql
n_setup=$(ls "$parts"/setup-*.sql | wc -l)
{
  echo "-- NEXA: part $((n_setup + 1)) of the setup (last). GENERATED by scripts/build-setup-sql.sh, do not edit."
  echo "begin;"
  cat supabase/seeds/game_config.sql
  echo
  echo "$bootstrap"
  echo
  echo "commit;"
} > "$(printf "%s/setup-%02d.sql" "$parts" "$((n_setup + 1))")"
echo "$parts: $(ls "$parts" | wc -l) files, largest $(wc -c "$parts"/*.sql | sort -n | tail -2 | head -1)"
