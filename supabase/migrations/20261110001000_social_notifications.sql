-- ---------------------------------------------------------------------------
-- Weekly league (ranking by portfolio growth in percent)
-- ---------------------------------------------------------------------------
create table public.league_seasons (
  id          uuid primary key default gen_random_uuid(),
  week_start  date not null unique,
  starts_at   timestamptz not null,
  ends_at     timestamptz not null,
  status      public.league_season_status not null default 'scheduled',
  winner_id   uuid references public.profiles (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  check (ends_at > starts_at)
);
alter table public.league_seasons enable row level security;
create index league_seasons_winner_idx on public.league_seasons (winner_id);
create index league_seasons_status_idx on public.league_seasons (status, ends_at);
comment on table public.league_seasons is 'One league season per calendar week (Europe/Berlin).';

-- Public standings: only percentage growth and rank, never absolute wealth.
create table public.league_entries (
  season_id   uuid not null references public.league_seasons (id) on delete cascade,
  player_id   uuid not null references public.profiles (id) on delete cascade,
  growth_bps  integer not null default 0,
  rank        integer,
  updated_at  timestamptz not null default now(),
  primary key (season_id, player_id)
);
alter table public.league_entries enable row level security;
create index league_entries_player_idx on public.league_entries (player_id);
create index league_entries_rank_idx on public.league_entries (season_id, growth_bps desc);
comment on table public.league_entries is 'Public weekly standings (growth in bps, rank). The friend league is this table filtered by friendships.';

-- Internal baselines (absolute money) behind the percentages.
create table public.league_entry_baselines (
  season_id             uuid not null,
  player_id             uuid not null,
  start_net_worth_cents bigint not null,
  net_inflow_cents      bigint not null default 0,
  current_net_worth_cents bigint not null,
  updated_at            timestamptz not null default now(),
  primary key (season_id, player_id),
  foreign key (season_id, player_id) references public.league_entries (season_id, player_id) on delete cascade
);
alter table public.league_entry_baselines enable row level security;
comment on table public.league_entry_baselines is 'Net worth baselines for league growth (income is neutralised via net_inflow_cents). Internal.';

