-- Guard for the one column clients may touch on notifications: once read,
-- always read, and nothing else changes for non-service callers.
create or replace function public.notifications_client_update_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if current_user = 'authenticated' then
    if old.read_at is not null and new.read_at is distinct from old.read_at then
      new.read_at := old.read_at;
    end if;
    if new.read_at is not null and new.read_at > now() then
      new.read_at := now();
    end if;
  end if;
  return new;
end;
$$;

create trigger notifications_client_update_guard
  before update on public.notifications
  for each row execute function public.notifications_client_update_guard();
