create table public.friendships (
  id            uuid primary key default gen_random_uuid(),
  requester_id  uuid not null references public.profiles (id) on delete cascade,
  addressee_id  uuid not null references public.profiles (id) on delete cascade,
  status        public.friendship_status not null default 'pending',
  request_id    uuid not null default gen_random_uuid(),
  responded_at  timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  check (requester_id <> addressee_id)
);
alter table public.friendships enable row level security;
-- one relationship per unordered pair
create unique index friendships_pair_uq on public.friendships (least(requester_id, addressee_id), greatest(requester_id, addressee_id));
create index friendships_requester_idx on public.friendships (requester_id, status);
create index friendships_addressee_idx on public.friendships (addressee_id, status);
comment on table public.friendships is 'Friend requests and friendships (one row per pair).';

create or replace function public.are_friends(p_a uuid, p_b uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select ((select auth.uid()) is null or (select auth.uid()) in (p_a, p_b))
     and exists (
    select 1 from public.friendships f
     where f.status = 'accepted'
       and least(f.requester_id, f.addressee_id) = least(p_a, p_b)
       and greatest(f.requester_id, f.addressee_id) = greatest(p_a, p_b)
  );
$$;
comment on function public.are_friends(uuid, uuid) is 'RLS helper: both players are accepted friends. A JWT caller may only ask about pairs that include themselves.';

