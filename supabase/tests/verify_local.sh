#!/usr/bin/env bash
# =============================================================================
# NEXA · local schema verification on a throwaway PostgreSQL cluster
# =============================================================================
# Needs only the PostgreSQL 16 server binaries (no Docker, no Supabase CLI).
#   1. initdb into a temp directory and start a private server
#   2. create a minimal Supabase stub (roles, auth schema, auth.uid())
#   3. apply all migrations, seed.sql and seeds/artworks.sql with ON_ERROR_STOP
#   4. run the SQL assertions in supabase/tests/[1-4]*.sql, then (older
#      database mode only) apply update-to-latest.sql, then [5-9]*.sql
#   5. stop and delete the cluster
# Exits non-zero on the first failure.
#
# Environment:
#   PG_BIN         directory with initdb/pg_ctl/psql (default /usr/lib/postgresql/16/bin)
#   NEXA_PG_DIR    work directory (default: mktemp)
#   NEXA_PG_PORT   port (default 54329)
#   NEXA_KEEP=1    keep the cluster running for inspection
#   NEXA_SINGLE_TX=0  apply migrations in autocommit mode instead of one transaction per file
#   NEXA_MIGRATIONS_UPTO=<timestamp>  apply only migrations up to this one (simulates
#                  an older database that is then brought up to date by update-to-latest.sql)
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUPABASE_DIR="$(dirname "$SCRIPT_DIR")"
PG_BIN="${PG_BIN:-/usr/lib/postgresql/16/bin}"
PORT="${NEXA_PG_PORT:-54329}"
WORK_DIR="${NEXA_PG_DIR:-$(mktemp -d "${TMPDIR:-/tmp}/nexa-pg.XXXXXX")}"
DATA_DIR="$WORK_DIR/data"
LOG_FILE="$WORK_DIR/postgres.log"
DB=nexa_verify

if [[ ! -x "$PG_BIN/initdb" ]]; then
  PG_BIN="$(dirname "$(command -v initdb 2>/dev/null || true)")"
  [[ -x "$PG_BIN/initdb" ]] || { echo "PostgreSQL binaries not found; set PG_BIN" >&2; exit 2; }
fi

mkdir -p "$WORK_DIR"

# PostgreSQL refuses to run as root. As root we either delegate the server
# commands to the "postgres" OS user (if it can reach the work directory) or
# run them inside a user namespace that maps root to an unprivileged uid.
RUNNER=direct
if [[ "$(id -u)" -eq 0 ]]; then
  if id postgres >/dev/null 2>&1 && chown postgres "$WORK_DIR" 2>/dev/null \
     && runuser -u postgres -- test -w "$WORK_DIR" 2>/dev/null; then
    RUNNER=runuser
  elif unshare -U --map-user=1000 --map-group=1000 true 2>/dev/null; then
    chown root "$WORK_DIR" 2>/dev/null || true
    RUNNER=unshare
  else
    echo "cannot drop root privileges (need the postgres user or unshare)" >&2
    exit 2
  fi
fi
as_pg() {
  case "$RUNNER" in
    runuser) runuser -u postgres -- "$@" ;;
    unshare) unshare -U --map-user=1000 --map-group=1000 -- "$@" ;;
    *)       "$@" ;;
  esac
}

cleanup() {
  local code=$?
  if [[ "${NEXA_KEEP:-0}" == "1" ]]; then
    echo "cluster kept: psql -h 127.0.0.1 -p $PORT -U postgres $DB   (data: $DATA_DIR)"
  else
    as_pg "$PG_BIN/pg_ctl" -D "$DATA_DIR" -m immediate -w stop >/dev/null 2>&1 || true
    rm -rf "$DATA_DIR" "$LOG_FILE" 2>/dev/null || true
    rmdir "$WORK_DIR" 2>/dev/null || true
  fi
  if [[ $code -eq 0 ]]; then
    echo "VERIFICATION PASSED"
  else
    echo "VERIFICATION FAILED (exit $code)" >&2
    [[ -f "$LOG_FILE" ]] && tail -n 20 "$LOG_FILE" >&2 || true
  fi
  exit $code
}
trap cleanup EXIT

echo "== initdb ($DATA_DIR)"
rm -rf "$DATA_DIR"
as_pg "$PG_BIN/initdb" -D "$DATA_DIR" -U postgres --auth=trust --encoding=UTF8 --locale=C >/dev/null
as_pg "$PG_BIN/pg_ctl" -D "$DATA_DIR" -l "$LOG_FILE" -w \
  -o "-p $PORT -c listen_addresses=127.0.0.1 -c unix_socket_directories='' -c timezone=UTC -c wal_level=logical" start >/dev/null

PSQL=("$PG_BIN/psql" -X -q -v ON_ERROR_STOP=1 -h 127.0.0.1 -p "$PORT" -U postgres)
"${PSQL[@]}" -d postgres -c "create database $DB"
PSQL+=(-d "$DB")

echo "== supabase stub"
"${PSQL[@]}" -f "$SCRIPT_DIR/00_supabase_stub.sql"

echo "== migrations"
shopt -s nullglob
for f in "$SUPABASE_DIR"/migrations/*.sql; do
  # NEXA_MIGRATIONS_UPTO=<timestamp> simulates an older database (tests the update file)
  if [[ -n "${NEXA_MIGRATIONS_UPTO:-}" && "$(basename "$f")" > "${NEXA_MIGRATIONS_UPTO}~" ]]; then
    echo "   $(basename "$f") (skipped: older database)"
    continue
  fi
  echo "   $(basename "$f")"
  # default: one transaction per migration file; NEXA_SINGLE_TX=0 runs
  # statement by statement (autocommit) to prove the files work either way
  if [[ "${NEXA_SINGLE_TX:-1}" == "1" ]]; then
    "${PSQL[@]}" -1 -f "$f"
  else
    "${PSQL[@]}" -f "$f"
  fi
done

echo "== seed.sql"
"${PSQL[@]}" -1 -f "$SUPABASE_DIR/seed.sql"
echo "== seed.sql (second run: must be idempotent)"
"${PSQL[@]}" -1 -f "$SUPABASE_DIR/seed.sql"
# The gallery (generated by scripts/gen-artworks.ts) needs the artworks table (M4a); an
# older database gets it from update-to-latest.sql below.
if [[ "$("${PSQL[@]}" -tAc "select to_regclass('public.artworks') is not null")" == "t" ]]; then
  echo "== seeds/artworks.sql (twice: must be idempotent)"
  "${PSQL[@]}" -1 -f "$SUPABASE_DIR/seeds/artworks.sql"
  "${PSQL[@]}" -1 -f "$SUPABASE_DIR/seeds/artworks.sql"
else
  echo "== seeds/artworks.sql (skipped: older database without artworks)"
fi

run_assertions() {
  for f in "$@"; do
    echo "-- $(basename "$f")"
    "${PSQL[@]}" -At -f "$f" 2>&1 | sed -e 's/^psql:[^ ]* NOTICE:  /   /' -e '/^$/d'
  done
}

echo "== assertions (schema, sign-up, RLS, seed)"
run_assertions "$SCRIPT_DIR"/[1-4]*.sql

if [[ -n "${NEXA_MIGRATIONS_UPTO:-}" ]]; then
  # An older database is brought up to date the way the owner does it: by
  # pasting update-to-latest.sql (twice: it must be idempotent).
  echo "== update-to-latest.sql on the older database (twice)"
  "${PSQL[@]}" -1 -f "$SUPABASE_DIR/update-to-latest.sql"
  "${PSQL[@]}" -1 -f "$SUPABASE_DIR/update-to-latest.sql"
fi

echo "== assertions (M1 market, trading, bonds, security)"
run_assertions "$SCRIPT_DIR"/[5-9]*.sql

if [[ -n "${NEXA_FIXTURE_DIR:-}" ]]; then
  echo "== RPC fixtures -> $NEXA_FIXTURE_DIR"
  mkdir -p "$NEXA_FIXTURE_DIR"
  chmod 777 "$NEXA_FIXTURE_DIR" 2>/dev/null || true
  "${PSQL[@]}" -v fixture_dir="$NEXA_FIXTURE_DIR" -f "$SCRIPT_DIR/fixtures.sql"
fi

# The assertions above set their own config rows, so the generated seed is checked last.
if [ -f "$SUPABASE_DIR/seeds/game_config.sql" ]; then
  echo "== seeds/game_config.sql (generated by pnpm db:config)"
  "${PSQL[@]}" -c "delete from public.game_config" -f "$SUPABASE_DIR/seeds/game_config.sql"
  "${PSQL[@]}" -1 -f "$SUPABASE_DIR/seeds/game_config.sql"
  "${PSQL[@]}" -tAc "select 'config sections: ' || count(*) || ', starting capital: ' || public.config_bigint('economy', '{startingCapitalCents}', -1) from public.game_config"
fi

# Runs last: the assertions above insert their own game_config rows.
echo "== update-to-latest.sql (twice: must be idempotent)"
"${PSQL[@]}" -1 -f "$SUPABASE_DIR/update-to-latest.sql"
"${PSQL[@]}" -1 -f "$SUPABASE_DIR/update-to-latest.sql"
"${PSQL[@]}" -tAc "select 'migration 1700 columns: ' || count(*) from information_schema.columns where table_name = 'company_quarter_reports' and column_name in ('market_segment','segment_demand_cents','uncovered_quarters','grace_quarters_left')"
"${PSQL[@]}" -tAc "select 'tutorial xp: ' || coalesce(value #>> '{xpSources,tutorial,xp}', 'MISSING') from public.game_config where key = 'progression'"
"${PSQL[@]}" -tAc "select 'M1 RPCs: ' || count(*) from pg_proc where pronamespace = 'public'::regnamespace and proname in ('get_market_snapshot','get_candles','get_order_book','get_security_details','get_my_portfolio','place_order','cancel_order','claim_vault','complete_tutorial','admin_set_paused','admin_run_tick','admin_close_quarter','market_tick','run_due_jobs')"
"${PSQL[@]}" -tAc "select 'candles: ' || count(*) || ', market tick: ' || (public.market_tick() ->> 'securities') || ' securities' from public.candles"

